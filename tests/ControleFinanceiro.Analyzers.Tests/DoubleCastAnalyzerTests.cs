using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class DoubleCastAnalyzerTests
{
    private readonly DoubleCastAnalyzer _analisador = new();

    [Theory]
    [InlineData(DuasConversoes)]
    [InlineData(DuasConversoesComParenteses)]
    public async Task Analisar_Quando_ConversaoDeConversao_Deve_Apontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0006");
    }

    [Theory]
    [InlineData(UmaConversao)]
    [InlineData(ConversaoDeExpressaoEntreParenteses)]
    public async Task Analisar_Quando_UmaConversao_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, DuasConversoesGeradas);

        apontados.Should().BeEmpty();
    }

    /// <summary>Vem desligada porque vale só em <c>src/</c>: o <c>.editorconfig</c> a liga lá.</summary>
    [Fact]
    public void Regra_Deve_VirDesligadaPorPadrao()
    {
        DoubleCastAnalyzer.Regra.IsEnabledByDefault.Should().BeFalse();
    }

    private const string DuasConversoes = """
        class C
        {
            int Converter(double valor)
            {
                return (int)(long)valor;
            }
        }
        """;

    private const string DuasConversoesComParenteses = """
        class C
        {
            int Converter(double valor)
            {
                return (int)((long)valor);
            }
        }
        """;

    private const string UmaConversao = """
        class C
        {
            int Converter(double valor)
            {
                return (int)valor;
            }
        }
        """;

    private const string ConversaoDeExpressaoEntreParenteses = """
        class C
        {
            int Converter(double valor)
            {
                return (int)(valor * 2);
            }
        }
        """;

    private const string DuasConversoesGeradas = """
        // <auto-generated/>
        class C
        {
            int Converter(double valor)
            {
                return (int)(long)valor;
            }
        }
        """;
}

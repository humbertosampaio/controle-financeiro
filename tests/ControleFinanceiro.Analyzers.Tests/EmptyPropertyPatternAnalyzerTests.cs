using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class EmptyPropertyPatternAnalyzerTests
{
    private readonly EmptyPropertyPatternAnalyzer _analisador = new();

    [Theory]
    [InlineData("valor is { } numero ? numero : 0")]
    [InlineData("valor switch { { } numero => numero, null => 0 }")]
    public async Task Analisar_Quando_PadraoVazioComVariavel_Deve_Apontar(string expressao)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Desembrulhar(expressao));

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0012");
    }

    [Theory]
    [InlineData("valor is int numero ? numero : 0")]
    [InlineData("valor is { } ? 1 : 0")]
    [InlineData("valor is var numero ? numero ?? 0 : 0")]
    public async Task Analisar_Quando_PadraoComTipoOuSemVariavel_Deve_NaoApontar(string expressao)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Desembrulhar(expressao));

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(
            _analisador,
            "// <auto-generated/>\n" + Desembrulhar("valor is { } numero ? numero : 0"));

        apontados.Should().BeEmpty();
    }

    private static string Desembrulhar(string expressao)
    {
        return $$"""
            class C
            {
                int Desembrulhar(int? valor)
                {
                    return {{expressao}};
                }
            }
            """;
    }
}

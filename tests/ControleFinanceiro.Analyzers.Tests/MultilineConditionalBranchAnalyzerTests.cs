using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class MultilineConditionalBranchAnalyzerTests
{
    private readonly MultilineConditionalBranchAnalyzer _analisador = new();

    [Theory]
    [InlineData(RamoVerdadeiroMultilinha)]
    [InlineData(RamoFalsoMultilinha)]
    public async Task Analisar_Quando_RamoEmVariasLinhas_Deve_Apontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0002");
    }

    [Theory]
    [InlineData(TernarioUmaLinha)]
    [InlineData(TernarioTresLinhasComRamosUmaLinha)]
    public async Task Analisar_Quando_CadaRamoEmUmaLinha_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, RamoMultilinhaGerado);

        apontados.Should().BeEmpty();
    }

    private const string RamoVerdadeiroMultilinha = """
        class C
        {
            int Escolher(bool condicao, int a, int b)
            {
                return condicao
                    ? a
                        + b
                    : b;
            }
        }
        """;

    private const string RamoFalsoMultilinha = """
        class C
        {
            int Escolher(bool condicao, int a, int b)
            {
                return condicao
                    ? a
                    : System.Math.Max(
                        a,
                        b);
            }
        }
        """;

    private const string TernarioUmaLinha = """
        class C
        {
            int Escolher(bool condicao, int a, int b)
            {
                return condicao ? a : b;
            }
        }
        """;

    private const string TernarioTresLinhasComRamosUmaLinha = """
        class C
        {
            int Escolher(bool condicao, int a, int b)
            {
                return condicao
                    ? a + b
                    : System.Math.Max(a, b);
            }
        }
        """;

    private const string RamoMultilinhaGerado = """
        // <auto-generated/>
        class C
        {
            int Escolher(bool condicao, int a, int b)
            {
                return condicao
                    ? a
                        + b
                    : b;
            }
        }
        """;
}

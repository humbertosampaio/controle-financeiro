using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class MultilineExpressionBodyAnalyzerTests
{
    private readonly MultilineExpressionBodyAnalyzer _analisador = new();

    [Theory]
    [InlineData(MetodoMultilinha)]
    [InlineData(OperadorMultilinha)]
    [InlineData(ConversaoMultilinha)]
    [InlineData(FuncaoLocalMultilinha)]
    public async Task Analisar_Quando_ExpressaoEmVariasLinhas_Deve_Apontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0001");
    }

    [Theory]
    [InlineData(MetodoLinhaAssinatura)]
    [InlineData(MetodoLinhaAbaixoAssinatura)]
    public async Task Analisar_Quando_ExpressaoEmUmaLinha_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Theory]
    [InlineData(LambdaMultilinha)]
    [InlineData(PropriedadeMultilinha)]
    public async Task Analisar_Quando_LambdaOuPropriedadeEmVariasLinhas_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, MetodoGeradoMultilinha);

        apontados.Should().BeEmpty();
    }

    private const string MetodoMultilinha = """
        class C
        {
            int Somar(int a, int b) =>
                a
                + b;
        }
        """;

    private const string OperadorMultilinha = """
        class C
        {
            public static C operator +(C a, C b) => new C()
                ?? a;
        }
        """;

    private const string ConversaoMultilinha = """
        class C
        {
            public static explicit operator int(C c) => c.GetHashCode()
                + 1;
        }
        """;

    private const string FuncaoLocalMultilinha = """
        class C
        {
            void Executar()
            {
                int Dobro(int x) => x
                    * 2;
            }
        }
        """;

    private const string MetodoLinhaAssinatura = """
        class C
        {
            int Somar(int a, int b) => a + b;
        }
        """;

    private const string MetodoLinhaAbaixoAssinatura = """
        class C
        {
            int Somar(int a, int b) =>
                a + b;
        }
        """;

    private const string LambdaMultilinha = """
        using System;

        class C
        {
            Func<int, int> Dobro()
            {
                return x => x
                    * 2;
            }
        }
        """;

    private const string PropriedadeMultilinha = """
        class C
        {
            int Total => 1
                + 2;
        }
        """;

    private const string MetodoGeradoMultilinha = """
        // <auto-generated/>
        class C
        {
            int Somar(int a, int b) =>
                a
                + b;
        }
        """;
}

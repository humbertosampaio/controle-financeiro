using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class NamedLiteralArgumentAnalyzerTests
{
    private readonly NamedLiteralArgumentAnalyzer _analisador = new();

    [Theory]
    [InlineData("null")]
    [InlineData("true")]
    [InlineData("false")]
    [InlineData("1")]
    [InlineData("-0.5m")]
    [InlineData("[]")]
    public async Task Analisar_Quando_LiteralSemNome_Deve_Apontar(string literal)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Chamada($"valor, {literal}"));

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0011");
    }

    [Theory]
    [InlineData(ConstrutorComLiteral)]
    [InlineData(ChamadaBaseComLiteral)]
    [InlineData(ChamadaAninhadaAssercao)]
    public async Task Analisar_Quando_LiteralSemNomeOutraChamada_Deve_Apontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0011");
    }

    [Theory]
    [InlineData("valor, cartao: null")]
    [InlineData("valor, new int[0]")]
    [InlineData("valor, valor")]
    public async Task Analisar_Quando_ArgumentoNomeadoOuNaoLiteral_Deve_NaoApontar(string argumentos)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Chamada(argumentos));

        apontados.Should().BeEmpty();
    }

    [Theory]
    [InlineData(ArgumentoUnico)]
    [InlineData(ConstrutorData)]
    [InlineData(GuardClause)]
    [InlineData(ListaParams)]
    [InlineData(TheoryDataAdd)]
    [InlineData(CriacaoSmartEnum)]
    [InlineData(Atributo)]
    [InlineData(Assercao)]
    [InlineData(ChamadaDelegate)]
    public async Task Analisar_Quando_Excecao_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, "// <auto-generated/>\n" + Chamada("valor, null"));

        apontados.Should().BeEmpty();
    }

    private static string Chamada(string argumentos)
    {
        return $$"""
            class C
            {
                void Pagar(int valor, object? cartao)
                {
                }

                void Pagar(int valor, int[] cartao)
                {
                }

                void Usar(int valor)
                {
                    Pagar({{argumentos}});
                }
            }
            """;
    }

    private const string ConstrutorComLiteral = """
        class Parcela
        {
            public Parcela(int numero, bool paga)
            {
            }
        }

        class C
        {
            Parcela Criar(int numero)
            {
                return new Parcela(numero, true);
            }
        }
        """;

    private const string ChamadaBaseComLiteral = """
        class Base
        {
            protected Base(int numero, bool paga)
            {
            }
        }

        class Derivada : Base
        {
            public Derivada(int numero)
                : base(numero, false)
            {
            }
        }
        """;

    private const string ChamadaAninhadaAssercao = AssercaoDeclarada + """

        class C
        {
            int Calcular(int valor, int ordinal)
            {
                return valor;
            }

            void Testar(int valor)
            {
                valor.Should().Be(Calcular(valor, 1));
            }
        }
        """;

    private const string ArgumentoUnico = """
        class C
        {
            System.DateOnly Amanha(System.DateOnly hoje)
            {
                return hoje.AddDays(1);
            }
        }
        """;

    private const string ConstrutorData = """
        class C
        {
            System.DateOnly Data()
            {
                return new System.DateOnly(2026, 3, 5);
            }
        }
        """;

    private const string GuardClause = """
        class C
        {
            void Conferir(int ordinal)
            {
                System.ArgumentOutOfRangeException.ThrowIfLessThan(ordinal, 1);
            }
        }
        """;

    private const string ListaParams = """
        class C
        {
            int Somar(int inicial, params int[] valores)
            {
                return inicial;
            }

            int Usar(int inicial)
            {
                return Somar(inicial, 1, 2);
            }
        }
        """;

    private const string TheoryDataAdd = """
        namespace Xunit
        {
            public class TheoryData<T1, T2>
            {
                public void Add(T1 primeiro, T2 segundo)
                {
                }
            }
        }

        class C
        {
            void Montar(Xunit.TheoryData<int, bool> dados)
            {
                dados.Add(1, true);
            }
        }
        """;

    private const string CriacaoSmartEnum = """
        namespace Ardalis.SmartEnum
        {
            public abstract class SmartEnum<TEnum>
            {
                protected SmartEnum(string name, int value)
                {
                }
            }
        }

        sealed class TipoConta : Ardalis.SmartEnum.SmartEnum<TipoConta>
        {
            public static readonly TipoConta Corrente = new("Corrente", 1);

            private TipoConta(string name, int value)
                : base(name, value)
            {
            }
        }
        """;

    private const string Atributo = """
        [System.AttributeUsage(System.AttributeTargets.Class, AllowMultiple = false)]
        class MarcaAttribute : System.Attribute
        {
            public MarcaAttribute(int valor, bool ativo)
            {
            }
        }

        [Marca(1, true)]
        class C
        {
        }
        """;

    private const string Assercao = AssercaoDeclarada + """

        class C
        {
            void Testar(decimal valor)
            {
                valor.Should().BeApproximately(850m, 0.01m);
            }
        }
        """;

    private const string ChamadaDelegate = """
        class C
        {
            int Usar(System.Func<int, bool, int> calcular)
            {
                return calcular(1, true);
            }
        }
        """;

    /// <summary>Um <c>Should()</c> mínimo, declarado no trecho para ele não depender do FluentAssertions.</summary>
    private const string AssercaoDeclarada = """
        static class Assercoes
        {
            public static Assercao Should(this object valor)
            {
                return new Assercao();
            }
        }

        class Assercao
        {
            public void Be(object esperado)
            {
            }

            public void BeApproximately(decimal esperado, decimal precisao)
            {
            }
        }
        """;
}

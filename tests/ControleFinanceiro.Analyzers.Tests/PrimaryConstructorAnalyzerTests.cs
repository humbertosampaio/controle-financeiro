using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class PrimaryConstructorAnalyzerTests
{
    private readonly PrimaryConstructorAnalyzer _analisador = new();

    [Theory]
    [InlineData(ClasseComConstrutorPrimario)]
    [InlineData(StructComConstrutorPrimario)]
    public async Task Analisar_Quando_ConstrutorPrimario_Deve_Apontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0003");
    }

    [Fact]
    public async Task Analisar_Quando_ConstrutorComum_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, ClasseComConstrutorComum);

        apontados.Should().BeEmpty();
    }

    [Theory]
    [InlineData(RecordPosicional)]
    [InlineData(RecordStructPosicional)]
    public async Task Analisar_Quando_RecordPosicional_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, ClasseGeradaComConstrutorPrimario);

        apontados.Should().BeEmpty();
    }

    private const string ClasseComConstrutorPrimario = """
        class C(int valor)
        {
            int Valor() => valor;
        }
        """;

    private const string StructComConstrutorPrimario = """
        struct S(int valor)
        {
            int Valor() => valor;
        }
        """;

    private const string ClasseComConstrutorComum = """
        class C
        {
            private readonly int _valor;

            public C(int valor)
            {
                _valor = valor;
            }
        }
        """;

    private const string RecordPosicional = """
        record R(int Valor);
        """;

    private const string RecordStructPosicional = """
        record struct R(int Valor);
        """;

    private const string ClasseGeradaComConstrutorPrimario = """
        // <auto-generated/>
        class C(int valor)
        {
            int Valor() => valor;
        }
        """;
}

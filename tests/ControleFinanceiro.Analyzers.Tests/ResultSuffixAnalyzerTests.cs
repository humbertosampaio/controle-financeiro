using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class ResultSuffixAnalyzerTests
{
    private readonly ResultSuffixAnalyzer _analisador = new();

    [Theory]
    [InlineData(ClasseComSufixo)]
    [InlineData(RecordComSufixo)]
    [InlineData(InterfaceComSufixo)]
    public async Task Analisar_Quando_TipoTerminaEmResult_Deve_Apontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0009b");
    }

    [Theory]
    [InlineData(TipoComSufixoCamada)]
    [InlineData(TipoChamadoResult)]
    [InlineData(ResultNoMeioNome)]
    public async Task Analisar_Quando_TipoSemSufixoResult_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, ClasseGeradaComSufixo);

        apontados.Should().BeEmpty();
    }

    private const string ClasseComSufixo = """
        class ImportacaoResult
        {
        }
        """;

    private const string RecordComSufixo = """
        record ImportacaoResult(int Lidas);
        """;

    private const string InterfaceComSufixo = """
        interface IImportacaoResult
        {
        }
        """;

    private const string TipoComSufixoCamada = """
        class ExtratoImportadoDto
        {
        }
        """;

    private const string TipoChamadoResult = """
        class Result
        {
        }
        """;

    private const string ResultNoMeioNome = """
        class ResultadoImportacao
        {
        }
        """;

    private const string ClasseGeradaComSufixo = """
        // <auto-generated/>
        class ImportacaoResult
        {
        }
        """;
}

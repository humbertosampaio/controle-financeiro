using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class SiblingArgumentsAnalyzerTests
{
    private readonly SiblingArgumentsAnalyzer _analisador = new();

    [Theory]
    [InlineData(PrimeiroArgumentoLinhaChamada)]
    [InlineData(DoisArgumentosMesmaLinhaEUmSozinho)]
    [InlineData(ArgumentosColunasDiferentes)]
    [InlineData(ArgumentosDoisNiveisAbaixo)]
    [InlineData(ArgumentoDepoisLambdaMultilinha)]
    public async Task Analisar_Quando_ArgumentosForaMesmoGrau_Deve_Apontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0007");
    }

    [Theory]
    [InlineData(CadaArgumentoLinhaPropria)]
    [InlineData(TodosArgumentosLinhaAbaixo)]
    [InlineData(TodosArgumentosLinhaChamada)]
    [InlineData(LambdaMultilinhaLinhaChamada)]
    public async Task Analisar_Quando_ArgumentosMesmoGrau_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, PrimeiroArgumentoLinhaChamadaGerado);

        apontados.Should().BeEmpty();
    }

    private const string PrimeiroArgumentoLinhaChamada = """
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(1,
                    2,
                    3);
            }
        }
        """;

    private const string DoisArgumentosMesmaLinhaEUmSozinho = """
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(
                    1, 2,
                    3);
            }
        }
        """;

    private const string ArgumentosColunasDiferentes = """
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(
                    1,
                      2,
                    3);
            }
        }
        """;

    private const string ArgumentosDoisNiveisAbaixo = """
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(
                        1,
                        2,
                        3);
            }
        }
        """;

    private const string ArgumentoDepoisLambdaMultilinha = """
        using System;

        class C
        {
            int Aplicar(int a, Func<int, int> f, int b) => f(a) + b;

            int Usar()
            {
                return Aplicar(1, x =>
                {
                    return x * 2;
                }, 3);
            }
        }
        """;

    private const string CadaArgumentoLinhaPropria = """
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(
                    1,
                    2,
                    3);
            }
        }
        """;

    private const string TodosArgumentosLinhaAbaixo = """
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(
                    1, 2, 3);
            }
        }
        """;

    private const string TodosArgumentosLinhaChamada = """
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(1, 2, 3);
            }
        }
        """;

    private const string LambdaMultilinhaLinhaChamada = """
        using System;

        class C
        {
            int Aplicar(int a, Func<int, int> f) => f(a);

            int Usar()
            {
                return Aplicar(1, x =>
                {
                    return x * 2;
                });
            }
        }
        """;

    private const string PrimeiroArgumentoLinhaChamadaGerado = """
        // <auto-generated/>
        class C
        {
            int Somar(int a, int b, int c) => a + b + c;

            int Usar()
            {
                return Somar(1,
                    2,
                    3);
            }
        }
        """;
}

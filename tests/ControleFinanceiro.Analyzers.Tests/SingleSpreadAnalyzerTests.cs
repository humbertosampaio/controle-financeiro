using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class SingleSpreadAnalyzerTests
{
    private readonly SingleSpreadAnalyzer _analisador = new();

    [Fact]
    public async Task Analisar_Quando_SpreadSozinho_Deve_Apontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, SpreadSozinho);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0005");
    }

    [Theory]
    [InlineData(DoisSpreads)]
    [InlineData(SpreadComElemento)]
    [InlineData(ToArray)]
    public async Task Analisar_Quando_SpreadJuntaElementos_Deve_NaoApontar(string codigo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, codigo);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, SpreadSozinhoGerado);

        apontados.Should().BeEmpty();
    }

    private const string SpreadSozinho = """
        using System.Collections.Generic;

        class C
        {
            int[] Copiar(IEnumerable<int> numeros)
            {
                return [.. numeros];
            }
        }
        """;

    private const string DoisSpreads = """
        using System.Collections.Generic;

        class C
        {
            int[] Juntar(IEnumerable<int> a, IEnumerable<int> b)
            {
                return [.. a, .. b];
            }
        }
        """;

    private const string SpreadComElemento = """
        using System.Collections.Generic;

        class C
        {
            int[] Acrescentar(IEnumerable<int> numeros)
            {
                return [.. numeros, 0];
            }
        }
        """;

    private const string ToArray = """
        using System.Collections.Generic;
        using System.Linq;

        class C
        {
            int[] Copiar(IEnumerable<int> numeros)
            {
                return numeros.ToArray();
            }
        }
        """;

    private const string SpreadSozinhoGerado = """
        // <auto-generated/>
        using System.Collections.Generic;

        class C
        {
            int[] Copiar(IEnumerable<int> numeros)
            {
                return [.. numeros];
            }
        }
        """;
}

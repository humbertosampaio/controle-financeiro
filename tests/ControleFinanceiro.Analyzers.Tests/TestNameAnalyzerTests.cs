using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class TestNameAnalyzerTests
{
    private readonly TestNameAnalyzer _analisador = new();

    [Theory]
    [InlineData("Criar_DeveFalhar")]
    [InlineData("Criar_Quando_Vazio_DeveFalhar")]
    [InlineData("ConversaoImplicita_De_DateOnly_Deve_UtilizarMesEAno")]
    [InlineData("criar_Deve_Falhar")]
    [InlineData("Criar_Quando_Vazio")]
    public async Task Analisar_Quando_NomeForaFormato_Deve_Apontar(string nome)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Teste("Fact", nome));

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0009");
    }

    [Theory]
    [InlineData("Criar_Quando_Vazio_Deve_Falhar")]
    [InlineData("Criar_Deve_GerarIdVersao7")]
    public async Task Analisar_Quando_NomeNoFormato_Deve_NaoApontar(string nome)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Teste("Fact", nome));

        apontados.Should().BeEmpty();
    }

    [Theory]
    [InlineData("Theory")]
    [InlineData("AutoDataProprio")]
    public async Task Analisar_Quando_AtributoDerivaFact_Deve_Apontar(string atributo)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Teste(atributo, "Criar_DeveFalhar"));

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0009");
    }

    [Fact]
    public async Task Analisar_Quando_MetodoSemAtributoTeste_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, MetodoAuxiliarClasseTeste);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, NomeForaFormatoGerado);

        apontados.Should().BeEmpty();
    }

    private static string Teste(string atributo, string nome)
    {
        return AtributosXunit + $$"""

            class Testes
            {
                [{{atributo}}]
                public void {{nome}}()
                {
                }
            }
            """;
    }

    /// <summary>Os atributos do xUnit, declarados no trecho para ele não depender do pacote.</summary>
    private const string AtributosXunit = """
        using Xunit;

        namespace Xunit
        {
            public class FactAttribute : System.Attribute
            {
            }

            public class TheoryAttribute : FactAttribute
            {
            }
        }

        class AutoDataProprioAttribute : TheoryAttribute
        {
        }
        """;

    private const string NomeForaFormatoGerado = "// <auto-generated/>\n" + AtributosXunit + """

        class Testes
        {
            [Fact]
            public void Criar_DeveFalhar()
            {
            }
        }
        """;

    private const string MetodoAuxiliarClasseTeste = AtributosXunit + """

        class Testes
        {
            private static int criarValor()
            {
                return 1;
            }
        }
        """;
}

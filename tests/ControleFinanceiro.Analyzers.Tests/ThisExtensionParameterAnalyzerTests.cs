using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class ThisExtensionParameterAnalyzerTests
{
    private readonly ThisExtensionParameterAnalyzer _analisador = new();

    [Fact]
    public async Task Analisar_Quando_ExtensaoComThis_Deve_Apontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, ExtensaoComThis);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0004");
    }

    [Fact]
    public async Task Analisar_Quando_BlocoExtension_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, BlocoExtension);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, ExtensaoGeradaComThis);

        apontados.Should().BeEmpty();
    }

    private const string ExtensaoComThis = """
        static class Extensoes
        {
            public static int Dobro(this int valor)
            {
                return valor * 2;
            }
        }
        """;

    private const string BlocoExtension = """
        static class Extensoes
        {
            extension(int valor)
            {
                public int Dobro()
                {
                    return valor * 2;
                }
            }
        }
        """;

    private const string ExtensaoGeradaComThis = """
        // <auto-generated/>
        static class Extensoes
        {
            public static int Dobro(this int valor)
            {
                return valor * 2;
            }
        }
        """;
}

using Microsoft.CodeAnalysis;

namespace ControleFinanceiro.Analyzers.Tests;

public sealed class UnnecessaryValueAnalyzerTests
{
    private readonly UnnecessaryValueAnalyzer _analisador = new();

    [Theory]
    [InlineData("int resultado = quantidade.Value + 2;")]
    [InlineData("int resultado = quantidade.Value;")]
    [InlineData("int resultado = Dobrar(quantidade.Value);")]
    [InlineData("int resultado = tipo.Value;")]
    [InlineData("bool igual = tipo.Value == 1;")]
    [InlineData("string texto = $\"Cartão {sufixo.Value}\";")]
    public async Task Analisar_Quando_ValueDispensavel_Deve_Apontar(string instrucao)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Metodo(instrucao));

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0013");
    }

    [Fact]
    public async Task Analisar_Quando_ValueDispensavelRetorno_Deve_Apontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, RetornoComValue);

        apontados.Should().ContainSingle().Which.Id.Should().Be("CF0013");
    }

    [Theory]
    [InlineData("var resultado = quantidade.Value;")]
    [InlineData("object resultado = quantidade.Value;")]
    [InlineData("int resultado = sufixo.Value.Length;")]
    [InlineData("string texto = $\"Tipo {tipo.Value}\";")]
    [InlineData("string texto = \"Tipo \" + tipo.Value;")]
    [InlineData("int resultado = Repetir(quantidade.Value);")]
    [InlineData("System.Linq.Expressions.Expression<System.Func<Quantidade, int>> leitura = q => q.Value;")]
    [InlineData("int resultado = outro.Value;")]
    public async Task Analisar_Quando_ValueMudaResultado_Deve_NaoApontar(string instrucao)
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, Metodo(instrucao));

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_OperadorConversao_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(_analisador, TiposDeclarados);

        apontados.Should().BeEmpty();
    }

    [Fact]
    public async Task Analisar_Quando_CodigoGerado_Deve_NaoApontar()
    {
        Diagnostic[] apontados = await Analise.ApontarAsync(
            _analisador,
            "// <auto-generated/>\n" + Metodo("int resultado = quantidade.Value;"));

        apontados.Should().BeEmpty();
    }

    private static string Metodo(string instrucao)
    {
        return TiposDeclarados + $$"""

            class C
            {
                void Usar(Quantidade quantidade, SufixoCartao sufixo, TipoConta tipo, Outro outro)
                {
                    {{instrucao}}
                }

                int Dobrar(int valor)
                {
                    return valor * 2;
                }

                T Repetir<T>(T valor)
                {
                    return valor;
                }
            }
            """;
    }

    private const string RetornoComValue = TiposDeclarados + """

        class C
        {
            int Ler(Quantidade quantidade)
            {
                return quantidade.Value;
            }
        }
        """;

    /// <summary>
    /// As bases do CSharpFunctionalExtensions e do SmartEnum, com o operador implícito para o valor, declaradas no
    /// trecho para ele não depender dos pacotes. O <c>Outro</c> tem um <c>Value</c> sem ser nenhuma das duas.
    /// </summary>
    private const string TiposDeclarados = """
        namespace CSharpFunctionalExtensions
        {
            public abstract class SimpleValueObject<T>
            {
                protected SimpleValueObject(T value)
                {
                    Value = value;
                }

                public T Value { get; }

                public static implicit operator T(SimpleValueObject<T> valueObject)
                {
                    return valueObject.Value;
                }
            }
        }

        namespace Ardalis.SmartEnum
        {
            public abstract class SmartEnum<TEnum, TValue>
            {
                protected SmartEnum(string name, TValue value)
                {
                    Name = name;
                    Value = value;
                }

                public string Name { get; }

                public TValue Value { get; }

                public static implicit operator TValue(SmartEnum<TEnum, TValue> smartEnum)
                {
                    return smartEnum.Value;
                }
            }
        }

        sealed class Quantidade : CSharpFunctionalExtensions.SimpleValueObject<int>
        {
            public Quantidade(int valor)
                : base(valor)
            {
            }
        }

        sealed class SufixoCartao : CSharpFunctionalExtensions.SimpleValueObject<string>
        {
            public SufixoCartao(string valor)
                : base(valor)
            {
            }
        }

        sealed class TipoConta : Ardalis.SmartEnum.SmartEnum<TipoConta, int>
        {
            public TipoConta(string name, int value)
                : base(name, value)
            {
            }
        }

        sealed class Outro
        {
            public int Value { get; }

            public static implicit operator int(Outro outro)
            {
                return outro.Value;
            }
        }
        """;
}
